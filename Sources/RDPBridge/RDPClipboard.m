#define TAG CLIENT_TAG("mac.bridge.clipboard")

static const char *const FileGroupDescriptorName = "FileGroupDescriptorW";
/// On every pasteboard write of ours, so the poll doesn't send the server its own data back.
static NSPasteboardType const OwnMarkerType = @"hu.softworks.remotedesktop.rdp-clipboard";
/// Index of a promised file in the server's list, on each promise item.
static NSPasteboardType const FileIndexType = @"hu.softworks.remotedesktop.rdp-clipboard.index";
/// nspasteboard.org convention: clipboard managers skip these (reading would start a download).
static NSPasteboardType const TransientType = @"org.nspasteboard.TransientType";
static NSPasteboardType const AutoGeneratedType = @"org.nspasteboard.AutoGeneratedType";

static const NSUInteger MaxRemoteFiles = 100000;
static const NSUInteger MaxLocalFiles = 50000;
static const uint32_t ChunkSize = 1024 * 1024;
static const NSTimeInterval StallTimeout = 30;
/// Finder stops waiting for pasteboard data after about a minute; past this the user pastes again.
static const NSTimeInterval FinderPatience = 50;

typedef NS_ENUM(NSInteger, RequestKind) {
	RequestKindText,
	RequestKindFiles,
};

typedef NS_ENUM(NSInteger, DownloadState) {
	DownloadStateIdle,
	DownloadStateRunning,
	DownloadStateDone,
	DownloadStateFailed,
};

@implementation RDPClipboardTexts
@end

@interface RDPClipboard ()
- (UINT)monitorReady;
- (UINT)serverCapabilities:(const CLIPRDR_CAPABILITIES *)capabilities;
- (UINT)serverFormatList:(const CLIPRDR_FORMAT_LIST *)formatList;
- (UINT)serverFormatDataRequest:(const CLIPRDR_FORMAT_DATA_REQUEST *)request;
- (UINT)serverFormatDataResponse:(const CLIPRDR_FORMAT_DATA_RESPONSE *)response;
- (UINT)serverFileContentsResponse:(const CLIPRDR_FILE_CONTENTS_RESPONSE *)response;
@end

static RDPClipboard *clipboard_of(CliprdrClientContext *cliprdr)
{
	/* FreeRDP's Mac clipboard clears `custom` when the channel closes. */
	if (!cliprdr || !cliprdr->custom)
		return nil;
	return (__bridge RDPClipboard *)cliprdr_file_context_get_context(
	    (CliprdrFileContext *)cliprdr->custom);
}

static UINT on_monitor_ready(CliprdrClientContext *cliprdr, const CLIPRDR_MONITOR_READY *e)
{
	(void)e;
	return [clipboard_of(cliprdr) monitorReady];
}

static UINT on_server_capabilities(CliprdrClientContext *cliprdr, const CLIPRDR_CAPABILITIES *e)
{
	return [clipboard_of(cliprdr) serverCapabilities:e];
}

static UINT on_server_format_list(CliprdrClientContext *cliprdr, const CLIPRDR_FORMAT_LIST *e)
{
	return [clipboard_of(cliprdr) serverFormatList:e];
}

static UINT on_server_format_list_response(CliprdrClientContext *cliprdr,
                                           const CLIPRDR_FORMAT_LIST_RESPONSE *e)
{
	(void)cliprdr;
	(void)e;
	return CHANNEL_RC_OK;
}

static UINT on_server_format_data_request(CliprdrClientContext *cliprdr,
                                          const CLIPRDR_FORMAT_DATA_REQUEST *e)
{
	return [clipboard_of(cliprdr) serverFormatDataRequest:e];
}

static UINT on_server_format_data_response(CliprdrClientContext *cliprdr,
                                           const CLIPRDR_FORMAT_DATA_RESPONSE *e)
{
	return [clipboard_of(cliprdr) serverFormatDataResponse:e];
}

static UINT on_server_file_contents_response(CliprdrClientContext *cliprdr,
                                             const CLIPRDR_FILE_CONTENTS_RESPONSE *e)
{
	return [clipboard_of(cliprdr) serverFileContentsResponse:e];
}

/// A Windows file name can't hold these; WinPR refuses the whole list when one does.
static BOOL is_windows_safe_name(NSString *name)
{
	static NSCharacterSet *invalid;
	static dispatch_once_t once;
	dispatch_once(&once, ^{
		NSMutableCharacterSet *set = [NSMutableCharacterSet characterSetWithCharactersInString:@"\\/:*?\"<>|"];
		[set addCharactersInRange:NSMakeRange(0, 0x20)];
		invalid = set;
	});
	return name.length > 0 && [name rangeOfCharacterFromSet:invalid].location == NSNotFound;
}

@implementation RDPClipboard
{
	NSURL *_folder;
	RDPClipboardTexts *_texts;
	RDPClipboardDownloader *_downloader;

	/* Guarded by @synchronized(self): touched from the channel thread and main. */
	CliprdrClientContext *_cliprdr;
	CliprdrFileContext *_file;
	wClipboard *_local;
	UINT32 _fileGroupId;
	UINT32 _uriListId;
	BOOL _ready;
	NSString *_localText;
	NSData *_localUriList;
	NSMutableArray<NSNumber *> *_pendingRequests;
	NSUInteger _generation;
	NSArray<RDPRemoteFile *> *_remoteFiles;

	/* Main thread only. */
	NSTimer *_pollTimer;
	NSInteger _seenChangeCount;
	NSInteger _promiseChangeCount;
	DownloadState _downloadState;
	NSUInteger _downloadGeneration;
	NSURL *_downloadedFolder;
	NSString *_downloadError;
	BOOL _waitCancelled;
	BOOL _waiting;
	NSPanel *_panel;
	NSProgressIndicator *_progress;
}

- (instancetype)initWithFolder:(NSURL *)folder texts:(RDPClipboardTexts *)texts
{
	self = [super init];
	if (self)
	{
		_folder = folder;
		_texts = texts;
		_pendingRequests = [NSMutableArray new];
		_seenChangeCount = -1;
		_promiseChangeCount = -1;
	}
	return self;
}

#pragma mark Channel thread

- (void)attach:(CliprdrClientContext *)cliprdr
{
	@synchronized(self)
	{
		_file = cliprdr_file_context_new((__bridge void *)self);
		_local = ClipboardCreate();
		if (!_file || !_local || !cliprdr_file_context_set_locally_available(_file, TRUE) ||
		    !cliprdr_file_context_init(_file, cliprdr))
		{
			/* Our callbacks find us through the file context: without it, keep FreeRDP's text clipboard. */
			WLog_ERR(TAG, "file clipboard unavailable");
			cliprdr_file_context_free(_file);
			_file = NULL;
			ClipboardDestroy(_local);
			_local = NULL;
			return;
		}
		_fileGroupId = ClipboardRegisterFormat(_local, FileGroupDescriptorName);
		_uriListId = ClipboardRegisterFormat(_local, "text/uri-list");
		/* cliprdr_file_context_init set cliprdr->custom and serves Lock / Unlock / FileContentsRequest
		 * (Mac → Windows files). */
		cliprdr->MonitorReady = on_monitor_ready;
		cliprdr->ServerCapabilities = on_server_capabilities;
		cliprdr->ServerFormatList = on_server_format_list;
		cliprdr->ServerFormatListResponse = on_server_format_list_response;
		cliprdr->ServerFormatDataRequest = on_server_format_data_request;
		cliprdr->ServerFormatDataResponse = on_server_format_data_response;
		cliprdr->ServerFileContentsResponse = on_server_file_contents_response;
		_cliprdr = cliprdr;
		WLog_DBG(TAG, "took over the clipboard channel");
	}

	__weak RDPClipboard *weakSelf = self;
	_downloader = [[RDPClipboardDownloader alloc]
	       initWithRoot:_folder
	             sender:^(uint32_t streamId, uint32_t listIndex, RDPFileContentsKind kind,
	                      RDPFileRange range) {
		             [weakSelf requestStream:streamId index:listIndex kind:kind range:range];
	             }
	          chunkSize:ChunkSize
	     allowHugeFiles:NO
	       stallTimeout:StallTimeout];
}

- (void)detach
{
	[_downloader cancel];
	@synchronized(self)
	{
		if (_file)
		{
			(void)cliprdr_file_context_uninit(_file, _cliprdr);
			cliprdr_file_context_free(_file);
			_file = NULL;
		}
		if (_local)
		{
			ClipboardDestroy(_local);
			_local = NULL;
		}
		_cliprdr = NULL;
		_ready = NO;
		_remoteFiles = nil;
		_generation++;
		[_pendingRequests removeAllObjects];
	}
	dispatch_async(dispatch_get_main_queue(), ^{
		[self stopPolling];
		[self withdrawPromises:NO];
	});
}

- (void)sendClientCapabilities
{
	CLIPRDR_GENERAL_CAPABILITY_SET general = { 0 };
	general.capabilitySetType = CB_CAPSTYPE_GENERAL;
	general.capabilitySetLength = CB_CAPSTYPE_GENERAL_LEN;
	general.version = CB_CAPS_VERSION_2;
	general.generalFlags = CB_USE_LONG_FORMAT_NAMES | (_file ? cliprdr_file_context_current_flags(_file) : 0);
	CLIPRDR_CAPABILITIES capabilities = { 0 };
	capabilities.cCapabilitiesSets = 1;
	capabilities.capabilitySets = (CLIPRDR_CAPABILITY_SET *)&general;
	(void)_cliprdr->ClientCapabilities(_cliprdr, &capabilities);
}

- (UINT)monitorReady
{
	@synchronized(self)
	{
		if (!_cliprdr)
			return CHANNEL_RC_OK;
		[self sendClientCapabilities];
		_ready = YES;
		WLog_DBG(TAG, "monitor ready");
	}
	dispatch_async(dispatch_get_main_queue(), ^{
		self->_seenChangeCount = -1; /* announce whatever is on the pasteboard now */
		[self pasteboardChanged];
		[self startPolling];
	});
	return CHANNEL_RC_OK;
}

- (UINT)serverCapabilities:(const CLIPRDR_CAPABILITIES *)capabilities
{
	@synchronized(self)
	{
		const BYTE *cursor = (const BYTE *)capabilities->capabilitySets;
		for (UINT32 i = 0; cursor && i < capabilities->cCapabilitiesSets; i++)
		{
			const CLIPRDR_CAPABILITY_SET *set = (const CLIPRDR_CAPABILITY_SET *)cursor;
			if (set->capabilitySetType == CB_CAPSTYPE_GENERAL &&
			    set->capabilitySetLength >= CB_CAPSTYPE_GENERAL_LEN)
			{
				const CLIPRDR_GENERAL_CAPABILITY_SET *general = (const CLIPRDR_GENERAL_CAPABILITY_SET *)set;
				WLog_DBG(TAG, "server capabilities: flags 0x%08" PRIx32, general->generalFlags);
				if (_file)
					(void)cliprdr_file_context_remote_set_flags(_file, general->generalFlags);
				break;
			}
			cursor += set->capabilitySetLength;
		}
	}
	return CHANNEL_RC_OK;
}

- (UINT)serverFormatList:(const CLIPRDR_FORMAT_LIST *)formatList
{
	@synchronized(self)
	{
		if (!_cliprdr)
			return CHANNEL_RC_OK;
		CLIPRDR_FORMAT_LIST_RESPONSE response = { 0 };
		response.common.msgType = CB_FORMAT_LIST_RESPONSE;
		response.common.msgFlags = CB_RESPONSE_OK;
		(void)_cliprdr->ClientFormatListResponse(_cliprdr, &response);

		/* New remote clipboard: whatever was promised from the old one is gone. */
		_generation++;
		_remoteFiles = nil;
		[_downloader cancel];

		WLog_DBG(TAG, "server format list: %" PRIu32 " formats", formatList->numFormats);
		UINT32 fileGroupId = 0;
		BOOL hasText = NO;
		for (UINT32 i = 0; i < formatList->numFormats; i++)
		{
			const CLIPRDR_FORMAT *format = &formatList->formats[i];
			if (format->formatName && strcmp(format->formatName, FileGroupDescriptorName) == 0)
				fileGroupId = format->formatId;
			else if (format->formatId == CF_UNICODETEXT)
				hasText = YES;
		}
		if (fileGroupId != 0)
			[self requestFormat:fileGroupId kind:RequestKindFiles];
		else if (hasText)
			[self requestFormat:CF_UNICODETEXT kind:RequestKindText];
	}
	return CHANNEL_RC_OK;
}

- (void)requestFormat:(UINT32)formatId kind:(RequestKind)kind
{
	CLIPRDR_FORMAT_DATA_REQUEST request = { 0 };
	request.common.msgType = CB_FORMAT_DATA_REQUEST;
	request.requestedFormatId = formatId;
	/* Responses carry no format id: they come back in request order. */
	[_pendingRequests addObject:@(kind)];
	(void)_cliprdr->ClientFormatDataRequest(_cliprdr, &request);
}

- (void)respond:(const BYTE *)data length:(UINT32)length
{
	CLIPRDR_FORMAT_DATA_RESPONSE response = { 0 };
	response.common.msgType = CB_FORMAT_DATA_RESPONSE;
	response.common.msgFlags = data ? CB_RESPONSE_OK : CB_RESPONSE_FAIL;
	response.common.dataLen = data ? length : 0;
	response.requestedFormatData = data;
	(void)_cliprdr->ClientFormatDataResponse(_cliprdr, &response);
}

- (UINT)serverFormatDataRequest:(const CLIPRDR_FORMAT_DATA_REQUEST *)request
{
	@synchronized(self)
	{
		WLog_DBG(TAG, "server requests format 0x%08" PRIx32 " (text %s, files %s)", request->requestedFormatId,
		         _localText ? "yes" : "no", _localUriList ? "yes" : "no");
		if (!_cliprdr)
			return CHANNEL_RC_OK;
		if (request->requestedFormatId == CF_UNICODETEXT && _localText)
		{
			NSMutableData *data =
			    [[_localText dataUsingEncoding:NSUTF16LittleEndianStringEncoding] mutableCopy];
			[data appendBytes:"\0\0" length:2];
			[self respond:data.bytes length:(UINT32)data.length];
		}
		else if (request->requestedFormatId == _fileGroupId && _localUriList && _file && _local)
			[self respondWithLocalFileList];
		else
			[self respond:NULL length:0];
	}
	return CHANNEL_RC_OK;
}

/// FileGroupDescriptorW for the local files: WinPR builds the descriptors from the uri-list, and FreeRDP's
/// file helper indexes the same list to serve the contents.
- (void)respondWithLocalFileList
{
	const char *uris = _localUriList.bytes;
	const UINT32 length = (UINT32)_localUriList.length;
	BYTE *list = NULL;
	UINT32 listLength = 0;
	ClipboardLock(_local);
	if (cliprdr_file_context_update_client_data(_file, uris, length) &&
	    ClipboardSetData(_local, _uriListId, uris, length))
	{
		UINT32 size = 0;
		FILEDESCRIPTORW *descriptors = ClipboardGetData(_local, _fileGroupId, &size);
		if (descriptors)
		{
			const UINT error =
			    cliprdr_serialize_file_list_ex(cliprdr_file_context_remote_get_flags(_file), descriptors,
			                                   size / sizeof(FILEDESCRIPTORW), &list, &listLength);
			if (error != CHANNEL_RC_OK)
				WLog_WARN(TAG, "cannot serialize the file list: 0x%08X", error);
			free(descriptors);
		}
	}
	ClipboardUnlock(_local);
	[self respond:list length:listLength];
	free(list);
}

- (UINT)serverFormatDataResponse:(const CLIPRDR_FORMAT_DATA_RESPONSE *)response
{
	RequestKind kind;
	NSUInteger generation;
	@synchronized(self)
	{
		if (_pendingRequests.count == 0)
			return CHANNEL_RC_OK;
		kind = (RequestKind)_pendingRequests.firstObject.integerValue;
		[_pendingRequests removeObjectAtIndex:0];
		generation = _generation;
	}
	/* A refused response is not a protocol error; returning one would end the session. */
	if ((response->common.msgFlags & CB_RESPONSE_FAIL) || !response->requestedFormatData)
	{
		WLog_WARN(TAG, "server could not provide clipboard data");
		return CHANNEL_RC_OK;
	}
	NSData *data = [NSData dataWithBytes:response->requestedFormatData length:response->common.dataLen];

	if (kind == RequestKindText)
	{
		NSUInteger units = data.length / 2;
		const uint16_t *chars = data.bytes;
		for (NSUInteger i = 0; i < units; i++)
			if (chars[i] == 0)
			{
				units = i;
				break;
			}
		NSString *text = [[NSString alloc] initWithBytes:data.bytes
		                                          length:units * 2
		                                        encoding:NSUTF16LittleEndianStringEncoding];
		if (text)
			dispatch_async(dispatch_get_main_queue(), ^{
				[self writeText:text];
			});
		return CHANNEL_RC_OK;
	}

	NSString *error = nil;
	NSArray<RDPRemoteFile *> *files = [RDPClipboardFileList parse:data maxEntries:MaxRemoteFiles error:&error];
	if (!files)
	{
		WLog_WARN(TAG, "rejected the server's file list: %s", error.UTF8String);
		dispatch_async(dispatch_get_main_queue(), ^{
			if (self.onFileTransferEnded)
				self.onFileTransferEnded(error);
		});
		return CHANNEL_RC_OK;
	}
	@synchronized(self)
	{
		if (generation != _generation)
			return CHANNEL_RC_OK;
		_remoteFiles = files;
	}
	dispatch_async(dispatch_get_main_queue(), ^{
		[self promiseFiles:files generation:generation];
	});
	return CHANNEL_RC_OK;
}

- (void)requestStream:(uint32_t)streamId
                index:(uint32_t)listIndex
                 kind:(RDPFileContentsKind)kind
                range:(RDPFileRange)range
{
	@synchronized(self)
	{
		if (!_cliprdr)
		{
			[_downloader receiveStreamId:streamId ok:NO data:[NSData data]];
			return;
		}
		CLIPRDR_FILE_CONTENTS_REQUEST request = { 0 };
		request.common.msgType = CB_FILECONTENTS_REQUEST;
		request.streamId = streamId;
		request.listIndex = listIndex;
		request.dwFlags = kind == RDPFileContentsKindSize ? FILECONTENTS_SIZE : FILECONTENTS_RANGE;
		request.nPositionLow = range.positionLow;
		request.nPositionHigh = range.positionHigh;
		request.cbRequested = range.length;
		if (_cliprdr->ClientFileContentsRequest(_cliprdr, &request) != CHANNEL_RC_OK)
			[_downloader receiveStreamId:streamId ok:NO data:[NSData data]];
	}
}

- (UINT)serverFileContentsResponse:(const CLIPRDR_FILE_CONTENTS_RESPONSE *)response
{
	const BOOL ok = !(response->common.msgFlags & CB_RESPONSE_FAIL) && response->requestedData;
	NSData *data = ok ? [NSData dataWithBytes:response->requestedData length:response->cbRequested]
	                  : [NSData data];
	[_downloader receiveStreamId:response->streamId ok:ok data:data];
	return CHANNEL_RC_OK;
}

#pragma mark Main thread: Mac → server

/// NSPasteboard has no change notification. FreeRDP's own poll timer never starts (MRDPView's `resume` runs
/// before the view counts as connected), so the clipboard keeps its own, also during menu tracking.
- (void)startPolling
{
	if (_pollTimer)
		return;
	__weak RDPClipboard *weakSelf = self;
	_pollTimer = [NSTimer timerWithTimeInterval:0.5
	                                    repeats:YES
	                                      block:^(NSTimer *timer) {
		                                      (void)timer;
		                                      [weakSelf pasteboardChanged];
	                                      }];
	_pollTimer.tolerance = 0.1;
	[NSRunLoop.mainRunLoop addTimer:_pollTimer forMode:NSRunLoopCommonModes];
}

- (void)stopPolling
{
	[_pollTimer invalidate];
	_pollTimer = nil;
}

- (void)pasteboardChanged
{
	NSPasteboard *pasteboard = NSPasteboard.generalPasteboard;
	const NSInteger changeCount = pasteboard.changeCount;
	if (changeCount == _seenChangeCount)
		return;
	_seenChangeCount = changeCount;
	if ([pasteboard.types containsObject:OwnMarkerType])
		return;

	NSString *text = nil;
	NSData *uriList = nil;
	NSArray<NSURL *> *urls = [pasteboard readObjectsForClasses:@[ NSURL.class ]
	                                                   options:@{ NSPasteboardURLReadingFileURLsOnlyKey : @YES }];
	if (urls.count > 0)
		uriList = [self uriListFor:urls];
	else
		text = [pasteboard stringForType:NSPasteboardTypeString];

	@synchronized(self)
	{
		WLog_DBG(TAG, "pasteboard changed (ready %d): text %lu chars, files %s", _ready,
		         (unsigned long)text.length, uriList ? "yes" : "no");
		if (!_ready || !_cliprdr)
			return;
		if (_localUriList && _file)
			(void)cliprdr_file_context_clear(_file);
		_localText = text;
		_localUriList = uriList;

		CLIPRDR_FORMAT formats[1] = { 0 };
		CLIPRDR_FORMAT_LIST list = { 0 };
		list.common.msgType = CB_FORMAT_LIST;
		list.formats = formats;
		if (uriList)
		{
			formats[0].formatId = _fileGroupId;
			formats[0].formatName = (char *)FileGroupDescriptorName;
			list.numFormats = 1;
		}
		else if (text)
		{
			formats[0].formatId = CF_UNICODETEXT;
			list.numFormats = 1;
		}
		const UINT rc = _cliprdr->ClientFormatList(_cliprdr, &list);
		WLog_DBG(TAG, "announced %" PRIu32 " formats: 0x%08" PRIX32, list.numFormats, rc);
		if (_file)
			(void)cliprdr_file_context_notify_new_client_format_list(_file);
	}
}

/// `text/uri-list` for the copied files, or nil (with a message) when they can't go to Windows: names
/// Windows can't hold, symlinked folders (WinPR would follow them, possibly in a loop), or too many files.
- (NSData *)uriListFor:(NSArray<NSURL *> *)urls
{
	NSMutableString *list = [NSMutableString new];
	NSUInteger count = 0;
	NSString *problem = nil;
	for (NSURL *url in urls)
	{
		NSURL *fileURL = url.filePathURL;
		NSString *path = fileURL.path;
		if (!path || !is_windows_safe_name(path.lastPathComponent))
		{
			problem = path.lastPathComponent ?: url.absoluteString;
			break;
		}
		NSNumber *isDirectory = nil;
		[fileURL getResourceValue:&isDirectory forKey:NSURLIsDirectoryKey error:nil];
		count++;
		if (isDirectory.boolValue)
		{
			NSDirectoryEnumerator<NSURL *> *walk = [NSFileManager.defaultManager
			               enumeratorAtURL:fileURL
			    includingPropertiesForKeys:@[ NSURLIsSymbolicLinkKey ]
			                       options:0
			                  errorHandler:nil];
			for (NSURL *child in walk)
			{
				NSNumber *isLink = nil;
				[child getResourceValue:&isLink forKey:NSURLIsSymbolicLinkKey error:nil];
				if (isLink.boolValue || !is_windows_safe_name(child.lastPathComponent) || ++count > MaxLocalFiles)
				{
					problem = child.lastPathComponent;
					break;
				}
			}
		}
		if (problem)
			break;
		/* No trailing slash: WinPR would name a folder "" otherwise. */
		NSString *uri = [NSURL fileURLWithPath:path isDirectory:NO].absoluteString;
		[list appendFormat:@"%@\r\n", uri];
	}
	if (problem)
	{
		WLog_WARN(TAG, "files not offered to the server: %s", problem.UTF8String);
		if (self.onFileTransferEnded)
			self.onFileTransferEnded([NSString stringWithFormat:@"%@ cannot be copied to Windows (unsupported "
			                                                    @"name, link or too many files)",
			                                                    problem]);
		return nil;
	}
	return [list dataUsingEncoding:NSUTF8StringEncoding];
}

#pragma mark Main thread: server → Mac

- (void)writeText:(NSString *)text
{
	NSPasteboard *pasteboard = NSPasteboard.generalPasteboard;
	[pasteboard clearContents];
	[pasteboard setString:text forType:NSPasteboardTypeString];
	[pasteboard setString:@"" forType:OwnMarkerType];
	_seenChangeCount = pasteboard.changeCount;
}

/// One promise item per top-level entry; Finder's paste asks for the file URLs, which starts the download.
- (void)promiseFiles:(NSArray<RDPRemoteFile *> *)files generation:(NSUInteger)generation
{
	@synchronized(self)
	{
		if (generation != _generation)
			return;
	}
	_downloadState = DownloadStateIdle;
	_downloadGeneration = generation;
	_downloadedFolder = nil;
	_downloadError = nil;

	NSPasteboard *pasteboard = NSPasteboard.generalPasteboard;
	[pasteboard prepareForNewContentsWithOptions:NSPasteboardContentsCurrentHostOnly];
	NSMutableArray<NSPasteboardItem *> *items = [NSMutableArray new];
	[[RDPClipboardFileList topLevelIndicesOf:files] enumerateIndexesUsingBlock:^(NSUInteger index, BOOL *stop) {
		NSPasteboardItem *item = [NSPasteboardItem new];
		[item setDataProvider:self forTypes:@[ NSPasteboardTypeFileURL ]];
		[item setString:[NSString stringWithFormat:@"%lu", (unsigned long)index] forType:FileIndexType];
		[item setString:@"" forType:OwnMarkerType];
		[item setString:@"" forType:TransientType];
		[item setString:@"" forType:AutoGeneratedType];
		[items addObject:item];
	}];
	[pasteboard writeObjects:items];
	_seenChangeCount = pasteboard.changeCount;
	_promiseChangeCount = pasteboard.changeCount;
}

- (void)pasteboard:(NSPasteboard *)pasteboard
                  item:(NSPasteboardItem *)item
    provideDataForType:(NSPasteboardType)type
{
	NSArray<RDPRemoteFile *> *files;
	NSUInteger generation;
	@synchronized(self)
	{
		files = _remoteFiles;
		generation = _generation;
	}
	const NSUInteger index = (NSUInteger)[item stringForType:FileIndexType].integerValue;
	if (!files || generation != _downloadGeneration || index >= files.count)
		return; /* the session ended or the remote clipboard changed */

	if (_downloadState != DownloadStateDone)
		[self downloadAndWait:files generation:generation];
	if (_downloadState != DownloadStateDone)
		return;
	NSURL *url = [_downloadedFolder URLByAppendingPathComponent:files[index].path
	                                                isDirectory:files[index].isDirectory];
	[item setString:url.absoluteString forType:NSPasteboardTypeFileURL];
}

/// Downloads the list (or joins a running download) and waits, keeping the run loop going: Finder is
/// blocked in its paste meanwhile. A progress panel with Cancel appears when it takes a while.
- (void)downloadAndWait:(NSArray<RDPRemoteFile *> *)files generation:(NSUInteger)generation
{
	if (_downloadState != DownloadStateRunning)
	{
		_downloadState = DownloadStateRunning;
		_downloadError = nil;
		[_downloader downloadFiles:files
		                completion:^(NSURL *folder, NSString *error) {
			                dispatch_async(dispatch_get_main_queue(), ^{
				                [self downloadEnded:folder error:error generation:generation];
			                });
		                }];
	}
	_waitCancelled = NO;
	_waiting = YES;
	NSDate *start = [NSDate date];
	NSModalSession session = NULL;
	while (_downloadState == DownloadStateRunning && !_waitCancelled)
	{
		const NSTimeInterval waited = -start.timeIntervalSinceNow;
		if (!session && waited > 0.5)
			session = [self beginProgressPanel];
		if (session)
		{
			[self updateProgress];
			if ([NSApp runModalSession:session] != NSModalResponseContinue)
				break;
		}
		if (waited > FinderPatience)
			break; /* Finder has given up; the download goes on and the user pastes again */
		/* Also serves the main queue: the download's completion and the session's painting. */
		(void)CFRunLoopRunInMode(kCFRunLoopDefaultMode, 0.05, true);
	}
	_waiting = NO;
	if (session)
	{
		[NSApp endModalSession:session];
		[_panel orderOut:nil];
	}
	if (_waitCancelled)
		[_downloader cancel];
}

- (void)downloadEnded:(NSURL *)folder error:(NSString *)error generation:(NSUInteger)generation
{
	if (generation != _downloadGeneration || _downloadState != DownloadStateRunning)
	{
		if (folder)
			[NSFileManager.defaultManager removeItemAtURL:folder error:nil];
		return;
	}
	const BOOL nobodyWaiting = !_waiting;
	_downloadState = folder ? DownloadStateDone : DownloadStateFailed;
	_downloadedFolder = folder;
	_downloadError = error;
	if (error && ![error isEqualToString:@"cancelled"] && self.onFileTransferEnded)
		self.onFileTransferEnded(error);
	else if (folder && nobodyWaiting && self.onFileTransferEnded)
		self.onFileTransferEnded(nil);
	if (_downloadState == DownloadStateFailed)
		_downloadState = DownloadStateIdle; /* a later paste may try again */
}

- (NSModalSession)beginProgressPanel
{
	if (!_panel)
	{
		_panel = [[NSPanel alloc] initWithContentRect:NSMakeRect(0, 0, 360, 110)
		                                    styleMask:NSWindowStyleMaskTitled
		                                      backing:NSBackingStoreBuffered
		                                        defer:NO];
		_panel.title = _texts.progressTitle;
		NSView *content = _panel.contentView;
		NSTextField *label = [NSTextField labelWithString:_texts.progressTitle];
		label.frame = NSMakeRect(20, 72, 320, 18);
		_progress = [[NSProgressIndicator alloc] initWithFrame:NSMakeRect(20, 48, 320, 16)];
		_progress.indeterminate = NO;
		_progress.minValue = 0;
		_progress.maxValue = 1;
		NSButton *cancel = [NSButton buttonWithTitle:_texts.cancel target:self action:@selector(cancelWait:)];
		cancel.keyEquivalent = @"\e";
		[cancel sizeToFit];
		cancel.frame = NSMakeRect(340 - NSWidth(cancel.frame), 10, NSWidth(cancel.frame), NSHeight(cancel.frame));
		[content addSubview:label];
		[content addSubview:_progress];
		[content addSubview:cancel];
		[_panel center];
	}
	[self updateProgress];
	return [NSApp beginModalSessionForWindow:_panel];
}

- (void)updateProgress
{
	const uint64_t total = _downloader.bytesTotal;
	_progress.doubleValue = total > 0 ? (double)_downloader.bytesDone / (double)total : 0;
}

- (void)cancelWait:(id)sender
{
	(void)sender;
	_waitCancelled = YES;
}

/// Drops our file items from the pasteboard if they are still there: undownloaded promises can no longer be
/// served once the channel is gone; with `all`, downloaded ones too (their folder is about to be deleted).
- (void)withdrawPromises:(BOOL)all
{
	NSPasteboard *pasteboard = NSPasteboard.generalPasteboard;
	if (_promiseChangeCount >= 0 && pasteboard.changeCount == _promiseChangeCount &&
	    (all || _downloadState != DownloadStateDone))
		[pasteboard clearContents];
	_promiseChangeCount = -1;
}

- (void)stop
{
	[self stopPolling];
	_waitCancelled = YES;
	[_downloader cancel];
	@synchronized(self)
	{
		_generation++;
		_remoteFiles = nil;
	}
	[self withdrawPromises:YES];
	[NSFileManager.defaultManager removeItemAtURL:_folder error:nil];
}

+ (void)purgeStaleFoldersIn:(NSURL *)root
{
	NSArray<NSURL *> *folders = [NSFileManager.defaultManager contentsOfDirectoryAtURL:root
	                                                       includingPropertiesForKeys:nil
	                                                                          options:0
	                                                                            error:nil];
	for (NSURL *folder in folders)
	{
		/* <pid>-<uuid> */
		const pid_t pid = (pid_t)[folder.lastPathComponent integerValue];
		if (pid > 0 && pid != getpid() && kill(pid, 0) != 0 && errno == ESRCH)
			[NSFileManager.defaultManager removeItemAtURL:folder error:nil];
	}
}

